static UiLanguage g_lang = LANG_CS;
static int g_override = -1;

void i18n_set_language(UiLanguage lang) { g_lang = lang; }
UiLanguage i18n_language(void) { return g_lang; }

const char* i18n_code(UiLanguage lang) { return lang == LANG_EN ? "en" : "cs"; }

bool i18n_parse(const char* code, UiLanguage* out)
{
    if (!code) return false;
    if (_stricmp(code, "cs") == 0) { *out = LANG_CS; return true; }
    if (_stricmp(code, "en") == 0) { *out = LANG_EN; return true; }
    return false;
}

UiLanguage i18n_system_language(void)
{
#ifdef _WIN32
    // the display language of Windows only (not the regional format)
    int primary = PRIMARYLANGID(GetUserDefaultUILanguage());
    return primary == LANG_CZECH || primary == LANG_SLOVAK ? LANG_CS : LANG_EN;
#else
    const char* v = getenv("LC_ALL");
    if (!v || !*v) v = getenv("LC_MESSAGES");
    if (!v || !*v) v = getenv("LANG");
    return v && (strncmp(v, "cs", 2) == 0 || strncmp(v, "sk", 2) == 0) ? LANG_CS : LANG_EN;
#endif
}

void i18n_set_override(UiLanguage lang) { g_override = (int)lang; }

bool i18n_override(UiLanguage* out)
{
    if (g_override < 0) return false;
    *out = (UiLanguage)g_override;
    return true;
}

const char* tr_lang(const char* key, UiLanguage lang)
{
    if (lang == LANG_EN) return key;
    static std::unordered_map<std::string, const char*> map;
    if (map.empty())
        for (const Translation& t : k_table) map[t.key] = t.cs;
    auto it = map.find(key);
    return it != map.end() ? it->second : key;
}

const char* tr(const char* key) { return tr_lang(key, g_lang); }

const char* i18n_duplicate_key(void)
{
    std::unordered_map<std::string, int> seen;
    for (const Translation& t : k_table)
        if (seen[t.key]++) return t.key;
    return nullptr;
}

const char* i18n_key_at(int i)
{
    return i >= 0 && i < (int)(sizeof(k_table) / sizeof(k_table[0])) ? k_table[i].key : nullptr;
}

const char* tr_id(const char* key)
{
    static std::unordered_map<std::string, std::string> cache[2];   // nodes: c_str() stays valid
    std::unordered_map<std::string, std::string>& c = cache[g_lang == LANG_EN ? 1 : 0];
    auto it = c.find(key);
    if (it == c.end()) it = c.emplace(key, std::string(tr(key)) + "###" + key).first;
    return it->second.c_str();
}

// `s` against the pattern `p` of k_core: "%s" takes one character or more (the shortest that fits first), its text
// goes into `caps`.
static bool core_match(const char* p, const char* s, std::vector<std::string>& caps)
{
    while (*p && !(p[0] == '%' && p[1] == 's')) {
        if (*p != *s) return false;
        p++;
        s++;
    }
    if (!*p) return !*s;
    if (!*s) return false;
    size_t n = caps.size();
    for (const char* e = s + 1;; e++) {
        caps.push_back(std::string(s, (size_t)(e - s)));
        if (core_match(p + 2, e, caps)) return true;
        caps.resize(n);
        if (!*e) return false;
    }
}

std::string tr_core_lang(const std::string& text, UiLanguage lang)
{
    if (lang == LANG_EN || text.empty()) return text;
    std::vector<std::string> caps;
    for (const Translation& t : k_core) {
        caps.clear();
        if (!core_match(t.key, text.c_str(), caps)) continue;
        std::string out;
        size_t k = 0;
        for (const char* p = t.cs; *p; p++) {
            if (p[0] == '%' && p[1] == 's' && k < caps.size()) {
                out += tr_core_lang(caps[k++], lang);
                p++;
            } else {
                out += *p;
            }
        }
        return out;
    }
    const char* ui = tr_lang(text.c_str(), lang);   // a text the UI table has (the APS-5 demo...)
    if (ui != text.c_str()) return ui;
    size_t colon = text.find(": ");   // "<card or file>: <text>"
    if (colon != std::string::npos && colon > 0)
        return tr_core_lang(text.substr(0, colon), lang) + ": " + tr_core_lang(text.substr(colon + 2), lang);
    return text;
}

std::string tr_core(const std::string& text)
{
    return tr_core_lang(text, g_lang);
}

const char* i18n_core_at(int i, const char** cs)
{
    if (i < 0 || i >= (int)(sizeof(k_core) / sizeof(k_core[0]))) return nullptr;
    if (cs) *cs = k_core[i].cs;
    return k_core[i].key;
}
